"""Reproducibility table (paper 1, appendix) for 21 <= n <= 100.

python code/make_repro_table.py   -> output/repro_table.tex (paper 1, Appendix C, Table 9)

Columns
  source  : record (n <= 36, configurations/record_values.json) or ours (configurations/best/n{n}.json)
  exp 44  : certificate covering the current best (
            same n and input value or t_polished within 1e-8 relative), mode first/second order, or none
  exp 78  : yes       = certified on the stored coordinates of the current best
                        (certificates/exp78/kkt_certs.jsonl or kkt78_current.jsonl with t within 1e-8,
                        or recheck_2026-11-12.txt, which was run on the then-current bests)
            polished  = certified on the exp 44 polished centre (certificates/exp78/kkt78_polished.jsonl)
            o.s.      = out of scope (loaded constraints exceed 2 core + 1: multipliers not unique)
            no        = not run on the current best, or not certified
  exact   : minimal polynomial known (certificates/exp104/exact_forms.json, status 'proved exact');
            otherwise the degree bound of the unsuccessful search, or '--' if not searched
"""
import glob
import sys
import json
import os
import re
from fractions import Fraction as F

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hlib
C = hlib.CERT
R44 = f'{C}/exp44'
os.makedirs(os.path.join(hlib.REPO, 'output'), exist_ok=True)
OUT = os.path.join(hlib.REPO, 'output', 'repro_table.tex')


def cur(n):
    return hlib.current_value(n)


def rel(a, b):
    return abs(float(a) / float(b) - 1)


def tval(d):
    try:
        return float(F(d['t_polished']))
    except Exception:
        return float(d.get('input_value', 'nan'))


rows44 = []
for f in sorted(glob.glob(f'{R44}/certs*.jsonl')):
    if 'exp108' in f: continue      # n = 97 attempt (not certified) is not part of the table inputs
    for line in open(f):
        if line.strip():
            rows44.append(json.loads(line))


def jl(path):
    return [json.loads(l) for l in open(path) if l.strip()]


k78_first = jl(f'{C}/exp78/kkt_certs.jsonl')
k78_cur = jl(f'{C}/exp78/kkt78_current.jsonl')
k78_pol = jl(f'{C}/exp78/kkt78_polished.jsonl')
recheck = set()
for line in open(f'{C}/exp78/recheck_2026-11-12.txt'):
    m = re.match(r'n=(\d+) certified=True', line)
    if m:
        recheck.add(int(m.group(1)))

exact = {}
for e in json.load(open(f'{C}/exp104/exact_forms.json')):
    n = int(e['n'])
    if e['status'] == 'proved exact':
        exact[n] = f"yes (deg {e['degree']})"
    else:
        m = re.search(r'degree (\d+)', e['status'])
        exact.setdefault(n, f"no ($\\le{m.group(1)}$)" if m else 'no')

table = []
for n in range(21, 101):
    v = cur(n)
    src = 'record' if n <= 36 else 'ours'
    m = [d for d in rows44 if int(d['n']) == n and (rel(d['input_value'], v) < 1e-8 or rel(tval(d), v) < 1e-8)]
    ok = [d for d in m if str(d.get('certified')) == 'True']
    if ok:
        d = ok[-1]
        cert = {'first-order': '1st', 'second-order': '2nd'}[d['mode']]
        excess = int(d['loaded_ties']) + int(d['loaded_walls']) - (2 * int(d['n_core']) + 1)
    else:
        cert, excess = 'none', None
    good = lambda L: any(int(x['n']) == n and x.get('certified') is True and x.get('t') and rel(x['t'], v) < 1e-8 for x in L)
    if good(k78_first) or good(k78_cur) or n in recheck:
        k78 = 'yes'
    elif good(k78_pol):
        k78 = 'polished'
    elif excess is not None and excess > 0:
        k78 = 'o.s.'
    else:
        k78 = 'no'
    table.append((n, src, cert, k78, exact.get(n, '--')))

# two blocks of 40 rows side by side
half = len(table) // 2
lines = [r'\begin{tabular}{@{}rllll@{\hspace{2em}}rllll@{}}', r'\toprule',
         r'$n$ & source & exp.~44 & exp.~78 & exact & $n$ & source & exp.~44 & exp.~78 & exact \\', r'\midrule']
for a, b in zip(table[:half], table[half:]):
    lines.append(' & '.join(str(x) for x in a) + ' & ' + ' & '.join(str(x) for x in b) + r' \\')
lines += [r'\bottomrule', r'\end{tabular}']
with open(OUT, 'w') as fh:
    fh.write('% Generated by make_repro_table.py; do not edit by hand.\n' + '\n'.join(lines) + '\n')

from collections import Counter
print('exp44:', Counter(r[2] for r in table))
print('exp78:', Counter(r[3] for r in table))
print('exp78 21-64:', Counter(r[3] for r in table if r[0] <= 64))
print('o.s.:', [r[0] for r in table if r[3] == 'o.s.'])
print('no 21-64:', [r[0] for r in table if r[3] == 'no' and r[0] <= 64])
print('exact:', Counter(r[4] for r in table))
